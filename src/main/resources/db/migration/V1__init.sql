-- ---------- Umumiy ----------
CREATE TABLE kv (
    key   text  PRIMARY KEY,           -- 'settings', 'translations.uz', 'translations.ru', 'translations.en', 'secret'
    value jsonb NOT NULL
);

-- Atomik hisoblagichlar: hujjat raqamlari ('doc:RECEIPT') va kontent ID'lari ('content:products')
CREATE TABLE counters (
    name  text   PRIMARY KEY,
    value bigint NOT NULL
);

CREATE TABLE content_item (
    collection text    NOT NULL CHECK (collection IN ('banners', 'products', 'posts', 'news', 'reviews')),
    id         bigint  NOT NULL,
    position   integer NOT NULL,
    data       jsonb   NOT NULL,
    PRIMARY KEY (collection, id)
);
CREATE INDEX content_item_order ON content_item (collection, position);
-- Foydalanuvchi sharhi: userId bo'yicha tez topish (har kimda bitta sharh)
CREATE UNIQUE INDEX content_review_user ON content_item (((data ->> 'userId')::bigint))
    WHERE collection = 'reviews' AND data ? 'userId';

-- ---------- Xodimlar va mijozlar ----------
CREATE TABLE staff (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   text        NOT NULL UNIQUE,
    name       text        NOT NULL DEFAULT '',
    role       text        NOT NULL CHECK (role IN ('SUPER_ADMIN', 'ADMIN', 'BUXGALTER', 'SKLAD_WORKER')),
    grant_perms  jsonb     NOT NULL DEFAULT '[]',
    revoke_perms jsonb     NOT NULL DEFAULT '[]',
    active     boolean     NOT NULL DEFAULT true,
    hash       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE site_user (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   text        NOT NULL,
    hash       text        NOT NULL,
    blocked    boolean     NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX site_user_username_ci ON site_user (lower(username));

CREATE TABLE user_favorite (
    user_id    bigint  NOT NULL REFERENCES site_user (id) ON DELETE CASCADE,
    product_id bigint  NOT NULL,
    position   integer NOT NULL,
    PRIMARY KEY (user_id, product_id)
);

-- ---------- Xabarlar va media ----------
CREATE TABLE message (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    phone      text        NOT NULL,
    message    text        NOT NULL DEFAULT '',
    read       boolean     NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE media (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       text        NOT NULL CHECK (type IN ('image', 'video')),
    name       text        NOT NULL,
    url        text        NOT NULL,
    thumb      text,
    width      integer,
    height     integer,
    size       bigint      NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------- Ombor ----------
CREATE TABLE warehouse (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text    NOT NULL,
    address text    NOT NULL DEFAULT '',
    note    text    NOT NULL DEFAULT '',
    active  boolean NOT NULL DEFAULT true
);

CREATE TABLE supplier (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text    NOT NULL,
    phone   text    NOT NULL DEFAULT '',
    address text    NOT NULL DEFAULT '',
    note    text    NOT NULL DEFAULT '',
    active  boolean NOT NULL DEFAULT true
);

CREATE TABLE catalog_item (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku        text          NOT NULL,
    name       text          NOT NULL,
    category   text          NOT NULL DEFAULT '',
    unit       text          NOT NULL CHECK (unit IN ('pcs', 'kg', 'g', 'l', 'm', 'box', 'pack')),
    cost       numeric(14,4) NOT NULL DEFAULT 0 CHECK (cost >= 0),  -- kirimda oxirgi sotib olish narxi (2 xonadan ortiq bo'lishi mumkin)
    price      numeric(14,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    min_stock  numeric(14,2) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    image      text          NOT NULL DEFAULT '',
    note       text          NOT NULL DEFAULT '',
    active     boolean       NOT NULL DEFAULT true,
    created_at timestamptz   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX catalog_item_sku_ci ON catalog_item (lower(sku));

CREATE TABLE catalog_barcode (
    item_id  bigint  NOT NULL REFERENCES catalog_item (id) ON DELETE CASCADE,
    barcode  text    NOT NULL UNIQUE,
    position integer NOT NULL,
    PRIMARY KEY (item_id, barcode)
);

CREATE TABLE movement (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number           text        NOT NULL UNIQUE,   -- KR-00012
    type             text        NOT NULL CHECK (type IN ('RECEIPT', 'ISSUE', 'TRANSFER', 'WRITE_OFF', 'ADJUSTMENT')),
    date             date        NOT NULL,
    warehouse_id     bigint      NOT NULL REFERENCES warehouse (id),
    to_warehouse_id  bigint      REFERENCES warehouse (id),
    supplier_id      bigint      REFERENCES supplier (id),
    counterparty     text        NOT NULL DEFAULT '',
    reason           text        NOT NULL DEFAULT '',
    note             text        NOT NULL DEFAULT '',
    status           text        NOT NULL DEFAULT 'posted' CHECK (status IN ('posted', 'cancelled')),
    created_by_id    bigint      NOT NULL,
    created_by_name  text        NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    cancelled_by_id  bigint,
    cancelled_by_name text,
    cancelled_at     timestamptz,
    cancel_reason    text
);
CREATE INDEX movement_date ON movement (date);
CREATE INDEX movement_warehouse ON movement (warehouse_id);

CREATE TABLE movement_line (
    movement_id bigint        NOT NULL REFERENCES movement (id) ON DELETE CASCADE,
    line_no     integer       NOT NULL,
    item_id     bigint        NOT NULL REFERENCES catalog_item (id),
    qty         numeric(14,3) NOT NULL CHECK (qty <> 0),   -- ADJUSTMENT'da ishorali farq
    price       numeric(14,4) NOT NULL CHECK (price >= 0),
    PRIMARY KEY (movement_id, line_no)
);
CREATE INDEX movement_line_item ON movement_line (item_id);

-- Qoldiq hech qachon saqlanmaydi: faqat tasdiqlangan (bekor qilinmagan) hujjatlardan hisoblanadi.
CREATE VIEW stock_effect AS
    SELECT l.item_id, m.warehouse_id, CASE WHEN m.type IN ('RECEIPT', 'ADJUSTMENT') THEN l.qty ELSE -l.qty END AS delta
      FROM movement m JOIN movement_line l ON l.movement_id = m.id
     WHERE m.status = 'posted'
    UNION ALL
    SELECT l.item_id, m.to_warehouse_id, l.qty
      FROM movement m JOIN movement_line l ON l.movement_id = m.id
     WHERE m.status = 'posted' AND m.type = 'TRANSFER';

CREATE VIEW stock AS
    SELECT item_id, warehouse_id, SUM(delta) AS qty FROM stock_effect GROUP BY item_id, warehouse_id;

-- ---------- Buxgalteriya ----------
CREATE TABLE ledger_transaction (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date            date          NOT NULL,
    type            text          NOT NULL CHECK (type IN ('income', 'expense')),
    category        text          NOT NULL,
    amount          numeric(14,2) NOT NULL CHECK (amount > 0),
    method          text          NOT NULL CHECK (method IN ('cash', 'card', 'transfer')),
    counterparty    text          NOT NULL DEFAULT '',
    supplier_id     bigint        REFERENCES supplier (id),
    note            text          NOT NULL DEFAULT '',
    created_by_id   bigint        NOT NULL,
    created_by_name text          NOT NULL,
    created_at      timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX ledger_transaction_date ON ledger_transaction (date);
